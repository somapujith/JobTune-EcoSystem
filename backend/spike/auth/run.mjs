async function runE1Main(w) {
  const first = await getJson(w, '/e1');
  const beforeLogs = w.logs.length;
  let exitRes, exitErr = null;
  try {
    const rr = await fetch(w.base + '/e1/exit', { method: 'POST', signal: AbortSignal.timeout(30000) });
    const txt = await rr.text();
    let parsed = null; try { parsed = JSON.parse(txt); } catch { /* not JSON */ }
    exitRes = { httpStatus: rr.status, bodyIsHandlerJson: !!parsed, handlerCatchBlockRan: !!(parsed && parsed.outcome), bodyPrefix: txt.slice(0, 160), parsed };
  } catch (e) { exitErr = String(e.message || e); }
  await sleep(500);
  let after = null, afterErr = null;
  try { after = await getJson(w, '/e1'); } catch (e) { afterErr = String(e.message || e); }
  return {
    moduleLoad: first.moduleLoad, requestTime: first.requestTime, instanceIdFirst: first.instanceId,
    exitCall: exitRes || { fetchError: exitErr },
    afterExit: after ? { instanceIdSame: after.instanceId === first.instanceId, requestCounter: after.requestCounter, moduleLoadedAtSame: after.moduleLoadedAt === first.moduleLoadedAt } : { error: afterErr },
    workerStillServing: !!after, logsDuringExit: w.logs.slice(beforeLogs).slice(0, 25),
  };
}

