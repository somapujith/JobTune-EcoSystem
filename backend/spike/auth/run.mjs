const started = new Set();
function descendants(rootPid) {
  try {
    const ps = spawnSync('powershell', ['-NoProfile', '-Command',
      'Get-CimInstance Win32_Process | Select-Object ProcessId,ParentProcessId | ConvertTo-Json -Compress'],
      { encoding: 'utf8', windowsHide: true });
    const rows = JSON.parse(ps.stdout);
    const kids = new Map();
    for (const r of rows) { (kids.get(r.ParentProcessId) || kids.set(r.ParentProcessId, []).get(r.ParentProcessId)).push(r.ProcessId); }
    const out = []; const stack = [rootPid];
    while (stack.length) { const p = stack.pop(); for (const c of kids.get(p) || []) { out.push(c); stack.push(c); } }
    return out;
  } catch { return []; }
}
const alive = (pid) => { try { process.kill(pid, 0); return true; } catch { return false; } };
function killTree(pid) {
  if (process.platform === 'win32') spawnSync('taskkill', ['/PID', String(pid), '/T', '/F'], { stdio: 'ignore', windowsHide: true });
  else { try { process.kill(pid, 'SIGKILL'); } catch { /* gone */ } }
}
async function stopWorker(w) {
  if (!w || w.stopped) return { leftover: [] };
  w.stopped = true;
  const kids = descendants(w.proc.pid);
  killTree(w.proc.pid);
  await sleep(800);
  let leftover = [w.proc.pid, ...kids].filter(alive);
  for (const p of leftover) killTree(p);   // these are all descendants of the wrangler we started
  await sleep(300);
  leftover = [w.proc.pid, ...kids].filter(alive);
  started.delete(w.proc.pid);
  return { pid: w.proc.pid, descendants: kids, leftover };
}
async function freePort(start) {
  for (let p = start; p < start + 60; p++) {
    const ok = await new Promise((res) => { const s = createServer(); s.once('error', () => res(false)); s.listen(p, '127.0.0.1', () => s.close(() => res(true))); });
    if (ok) return p;
  }
  throw new Error('no free port near ' + start);
}

async function startWorker({ config, script, label, basePort = 8788 }) {
  const port = await freePort(basePort);
  const inspector = await freePort(9330 + Math.floor(Math.random() * 200));
  const args = [WRANGLER_JS, 'dev'];
  if (script) args.push(script);
  args.push('--local', '--port', String(port), '--ip', '127.0.0.1', '--inspector-port', String(inspector),
    '-c', `spike/auth/${config}`, '--persist-to', 'spike/auth/out/.wrangler-state',
    '--show-interactive-dev-session', 'false', '--log-level', 'log');
  const env = { ...process.env, CLOUDFLARE_LOAD_DEV_VARS_FROM_DOT_ENV: 'false', WRANGLER_SEND_METRICS: 'false', NO_COLOR: '1', FORCE_COLOR: '0' };
  for (const k of ['DATABASE_URL', 'JWT_SECRET', 'NEON_DATABASE_URL']) delete env[k];
  const proc = spawn(process.execPath, args, { cwd: BACKEND, env, stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true });
  const w = { proc, port, label, logs: [], stopped: false, base: `http://127.0.0.1:${port}`, exited: false };
  started.add(proc.pid);
  const onData = (buf) => { for (const line of String(buf).split(/\r?\n/)) if (line.trim()) w.logs.push(line); };
  proc.stdout.on('data', onData); proc.stderr.on('data', onData);
  proc.on('exit', (code) => { w.exited = true; w.exitCode = code; });
  return w;
}
async function waitReady(w, path = '/health', timeoutMs = 150000) {
  const t0 = Date.now();
  while (Date.now() - t0 < timeoutMs) {
    if (w.exited) return { ready: false, exited: true, exitCode: w.exitCode };
    try {
      const r = await fetch(w.base + path, { signal: AbortSignal.timeout(4000) });
      const text = await r.text();
      return { ready: true, status: r.status, body: text.slice(0, 600), ms: Date.now() - t0 };
    } catch { await sleep(500); }
  }
  return { ready: false, timeout: true };
}
