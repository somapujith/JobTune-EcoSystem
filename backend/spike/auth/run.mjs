  const sm = authSrc.match(/const signupSchema = Joi\.object\(\{[\s\S]*?\r?\n\}\);/);
  const lm = authSrc.match(/const loginSchema = Joi\.object\(\{[\s\S]*?\r?\n\}\);/);
  if (!sm || !lm) throw new Error('could not extract signupSchema/loginSchema from src/routes/auth.js');
  writeFileSync(resolve(HERE, 'generated-schemas.mjs'),
    `// GENERATED by run.mjs from backend/src/routes/auth.js (regex slice) -- do not edit by hand.\n` +
    `import Joi from 'joi';\n\n` +
    `export ${sm[0]}\n\nexport ${lm[0]}\n`);

  const mwSrc = readFileSync(resolve(BACKEND, 'src/middleware/auth.js'), 'utf8');
  const gm = mwSrc.match(/const JWT_SECRET = process\.env\.JWT_SECRET;[\s\S]*?process\.exit\(1\);\r?\n\}/);
  if (!gm) throw new Error('could not extract the JWT_SECRET guard from src/middleware/auth.js');
